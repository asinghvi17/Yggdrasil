using BinaryBuilder

const YGGDRASIL_DIR = "../.."
include(joinpath(YGGDRASIL_DIR, "platforms", "macos_sdks.jl"))

name = "Wasmer"
version = v"7.5.0"

sources = [
    # v7.5.0
    GitSource("https://github.com/wasmerio/wasmer.git",
              "82ff099e082da586b38af79986abbb8b677f8baf"; tag="v$(version)"),
    # Git submodule `lib/napi` of wasmer v7.5.0. It is a member of the cargo workspace,
    # so it has to be present for cargo to load the workspace, even though we don't build it.
    GitSource("https://github.com/wasmerio/napi",
              "82b328f50ddaac78de388b67b4707f21864b9245"),
    DirectorySource("./bundled"),
]

# Based on the `build-capi` and `package-capi` targets of wasmer/Makefile.
# Features:
# - `cranelift` is the only compiler backend: it cross-compiles with plain cargo, unlike
#   `llvm` (needs a matching LLVM toolchain for the target); `singlepass` is not supported
#   on every architecture we build for.
# - The `wasi` feature of the C API enables `wasmer-wasix/sys`, which includes `host-reqwest`
#   and thereby reqwest, rustls, `aws-lc-sys` (assembly needing a newer binutils) and
#   `rustls-platform-verifier` (needs a newer macOS SDK). The C API does not need HTTP
#   (it is only used to download webc packages), so the patch replaces
#   `sys` by the same list of wasix features minus `host-reqwest`, `journal` (does not
#   compile without the other features) and the mmap/mio ones that are not needed.
#   WASI itself (`wasi_env_new`, `wasi_get_imports`, ...) is unaffected.
# - `wasmer` (lib/api) has an unconditional `bindgen` build-dependency that is only used by the
#   `v8` backend. On a musl build host it uses clang-sys' `static` feature, which needs
#   `libclang.a`, so the second patch makes it optional (enabled by `v8` only).
# - On aarch64 macOS, wasmer-compiler registers compact unwind info with libunwind's
#   `__unw_add_find_dynamic_unwind_sections`, which is only in the macOS 14 libSystem, so the
#   default 11.1 SDK fails to link. We link against the 14.0 SDK and so require macOS 14.
#   x86_64 macOS doesn't use compact unwind and keeps the default SDK and deployment target.
# - On riscv64, cc-rs (`wasmer-compiler`'s `libunwind.c`, `zstd-sys`, ...) passes `-march=rv64gc`,
#   which BinaryBuilder's compiler wrapper rejects (it already targets riscv64gc). So cc-rs'
#   default flags are disabled there, and the ones that matter are passed explicitly.
# - `wasi` enables WASI/WASIX (`wasi_*` functions), `wat` enables `wat2wasm` and
#   `wasm_module_new` on text input, `middlewares` is part of upstream's default set.
script = raw"""
cd ${WORKSPACE}/srcdir/wasmer/

atomic_patch -p1 ${WORKSPACE}/srcdir/patches/capi-no-wasix-networking.patch
atomic_patch -p1 ${WORKSPACE}/srcdir/patches/api-optional-bindgen.patch

# The `lib/napi` submodule is not part of the git checkout
rm -rf lib/napi
cp -r ${WORKSPACE}/srcdir/napi lib/napi

export CARGO_PROFILE_RELEASE_STRIP=debuginfo

if [[ "${target}" == riscv64-* ]]; then
    export CRATE_CC_NO_DEFAULTS=1
    export "CFLAGS_${rust_target//-/_}=-O2 -fPIC -ffunction-sections -fdata-sections"
    # `CRATE_CC_NO_DEFAULTS` also applies to the host (x86_64) build scripts
    export HOST_CFLAGS="-O2 -fPIC"
fi

cargo build \
    --release \
    --locked \
    --target ${rust_target} \
    --manifest-path lib/c-api/Cargo.toml \
    --no-default-features \
    --features wat,sys-default,compiler,cranelift,wasi,middlewares

# The library is named `wasmer`: libwasmer.so or libwasmer.dylib
mkdir -p ${libdir} ${includedir}
if [[ "${target}" == *-apple-* ]]; then
    install -Dvm 0755 "target/${rust_target}/release/libwasmer.dylib" "${libdir}/libwasmer.dylib"
else
    install -Dvm 0755 "target/${rust_target}/release/libwasmer.so" "${libdir}/libwasmer.so"
fi

# `wasmer.h` is generated by cbindgen in build.rs and copied to lib/c-api/
install -Dvm 0644 lib/c-api/wasmer.h "${includedir}/wasmer.h"
install -Dvm 0644 lib/c-api/wasmer_wasm.h "${includedir}/wasmer_wasm.h"
install -Dvm 0644 lib/c-api/tests/wasm-c-api/include/wasm.h "${includedir}/wasm.h"
install -Dvm 0644 lib/c-api/tests/wasm-c-api/include/wasm.hh "${includedir}/wasm.hh"

# The `wasm.h`/`wasm.hh` headers come from the bundled `wasm-c-api` project
install_license LICENSE
# (Both files are called LICENSE, so `install_license` can't install them together)
install -Dvm 0644 lib/c-api/tests/wasm-c-api/LICENSE "${prefix}/share/licenses/wasm-c-api/LICENSE"
"""

# `require_macos_sdk` unpacks the SDK and sets the deployment target on all macOS platforms,
# but only aarch64 needs it: restrict the helper's script to aarch64-apple-darwin.
sdk_sources, sdk_script = require_macos_sdk("14.0", Any[], "")
@assert occursin("== *-apple-darwin*", sdk_script)
sdk_script = replace(sdk_script, "== *-apple-darwin*" => "== aarch64-apple-darwin*")
sources = vcat(sources, sdk_sources)
script = sdk_script * script

# Wasmer's compilers only support 64-bit targets, and upstream builds the C API for x86_64,
# aarch64 and riscv64 in CI
platforms = supported_platforms(; exclude=(p -> !(arch(p) in ("x86_64", "aarch64", "riscv64"))))

# Filter Windows: Wasmer 7.5.0 rejects the Cranelift, Singlepass and LLVM compilers there
# with `compile_error!` ("Use the V8 backend instead"). The only Windows backend is V8,
# whose build script downloads a prebuilt `v8-windows-amd64.tar.xz` from
# https://github.com/wasmerio/wee8-custom-builds, which is not acceptable for Yggdrasil.
filter!(p -> !Sys.iswindows(p), platforms)

# Filter musl because Rust >= 1.84 (Wasmer 7.5 requires >= 1.96) assumes musl 1.2.3
# and emits hard references to `getrandom` and `posix_spawn_file_actions_addchdir_np`,
# which our musl 1.1.19 does not provide. Upstream also builds no musl C API.
# See https://github.com/rust-lang/rust/issues/141795
filter!(p -> libc(p) != "musl", platforms)

# NOTE: FreeBSD is not in upstream's release matrix, but `wasmer-vm` has explicit trap
# handler support for x86_64 and aarch64 FreeBSD. This is untested.

# NOTE: Headers get installed too but we aren't explicitly listing them as `FileProduct`s
products = [LibraryProduct("libwasmer", :libwasmer)]

dependencies = Dependency[]

build_tarballs(ARGS, name, version, sources, script, platforms, products, dependencies;
               compilers=[:c, :rust], julia_compat="1.6")
